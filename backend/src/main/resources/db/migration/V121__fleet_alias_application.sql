-- BL-DATA-01D: applies HUMAN-ACCEPTED alias candidates to the existing catalog (model + alias, optional evidence-backed
-- classification). One application per candidate (idempotent, resumable); immutable. Nothing is admitted or rated here.
CREATE TABLE app_fleet_alias_application (
 candidate_id uuid PRIMARY KEY REFERENCES app_fleet_alias_candidate(id),
 organization_id uuid NOT NULL REFERENCES app_organization(id),
 model_id uuid NOT NULL,
 observation_year integer NOT NULL CHECK (observation_year BETWEEN 1900 AND 2100),
 record_key text NOT NULL CHECK (record_key ~ '^[A-Z0-9][A-Z0-9._-]{0,99}$'),
 created_model boolean NOT NULL,
 created_alias boolean NOT NULL,
 classification_version integer CHECK (classification_version IS NULL OR classification_version > 0),
 applied_by uuid NOT NULL REFERENCES app_identity(id),
 applied_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 FOREIGN KEY (model_id, organization_id) REFERENCES app_fleet_model(id, organization_id)
);
CREATE TRIGGER app_fleet_alias_application_immutable
 BEFORE UPDATE OR DELETE ON app_fleet_alias_application
 FOR EACH ROW EXECUTE FUNCTION app_open_metering_immutable();

